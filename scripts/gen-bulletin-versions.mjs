import { readdirSync, statSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "public", "bulletin");
const extRe = /\.(png|jpe?g|gif|webp|svg)$/i;

const versions = readdirSync(dir)
  .filter((f) => extRe.test(f))
  .sort()
  .reduce((acc, f) => {
    acc[`/bulletin/${f}`] = String(Math.floor(statSync(join(dir, f)).mtimeMs));
    return acc;
  }, {});

const out = `// AUTO-GENERATED by scripts/gen-bulletin-versions.mjs — do not edit by hand
export const BULLETIN_VERSIONS: Record<string, string> = ${JSON.stringify(versions, null, 2)};
`;

const target = join(root, "app", "components", "bulletin-versions.ts");
writeFileSync(target, out);
console.log(`Generated ${Object.keys(versions).length} bulletin asset version(s) -> ${target}`);
